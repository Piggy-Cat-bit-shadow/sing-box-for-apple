#!/usr/bin/env python3
"""Compile and run the compact outbound-mode picker's own decision logic.

The compact picker is a SwiftUI view, and this host has no Xcode, so the view itself
cannot be instantiated here. What *can* be compiled and executed is the part of the
control that decides anything - which lists the compact shape is allowed to serve,
which third it marks, what a third is called, and which string a tap sends to the core.
None of that is SwiftUI: it is a handful of `private func`s on `HakoHomeView`.

So this gate does not re-implement them. It **extracts their source text** from
`HakoHomeView.swift` verbatim, compiles that text with the real Swift compiler, and
drives it through the cases the change has to satisfy. A re-implementation would only
prove that the re-implementation agrees with itself; extracted source is the shipped
code, and if it changes, the thing under test changes with it.

Usage:
    python check_compact_mode_picker.py [--root DIR] [--explain]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

# The methods the picker's decisions live in, in the order the harness declares them.
# Adding a decision to the view means adding it here; the gate fails loudly rather than
# silently testing a subset if one of them disappears.
REQUIRED_METHODS = (
    "conventionalModes",
    "currentMode",
    "canonicalMode",
    "modeTitle",
    "modeExplanation",
    "selectClashMode",
)

VIEW_FILE = os.path.join("ApplicationLibrary", "Views", "HakoStyle", "HakoHomeView.swift")
CATALOG_FILE = "Localizable.xcstrings"


class ExtractionError(RuntimeError):
    pass


def extract_method(source: str, name: str, path: str) -> str:
    """The full text of the `private func <name>(...)` declaration, body included.

    Braces inside string literals and comments are counted like any other brace. That
    is wrong in general and right here: the declarations this gate extracts contain no
    braces in their strings, and the alternative - a Swift lexer - is a second piece of
    machinery to keep in step with the first. Balance is checked, so a mis-parse is an
    error rather than a quietly truncated function.
    """
    match = re.search(r"^[ \t]*private func %s\b" % re.escape(name), source, re.MULTILINE)
    if match is None:
        raise ExtractionError(
            "%s: no `private func %s` - the picker's decision logic has moved, and this "
            "gate is no longer testing the shipped code" % (path, name)
        )
    depth = 0
    index = source.index("{", match.start())
    for position in range(index, len(source)):
        character = source[position]
        if character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth == 0:
                return source[match.start():position + 1]
    raise ExtractionError("%s: `%s` never closes" % (path, name))


HARNESS_HEADER = """\
// Generated by scripts/dev/check_compact_mode_picker.py. Not a source file.
//
// Everything below `enum Extracted` is the verbatim text of the methods named in
// REQUIRED_METHODS, lifted out of HakoHomeView.swift. `Probe` is the smallest thing
// that can stand in for the rest of the view: the two pieces of mode state and the
// recorder for what a tap sends.
import Foundation

struct AlertState {
    let action: String
    let error: Error
}

enum Variant {
    static let screenshotMode = false
}

struct CommandTarget {
    static var sent: [String] = []
    static var failure: Error?
    static func standaloneClient() -> CommandTarget { CommandTarget() }
    func setClashMode(_ mode: String) throws {
        if let failure = CommandTarget.failure { throw failure }
        CommandTarget.sent.append(mode)
    }
}

/// `withAnimation` is SwiftUI's, and this host has no SwiftUI. What the extracted
/// `selectClashMode` is being asked here is which value it settles on, not how it gets
/// there, so running the closure immediately is the whole of the stand-in's job.
func withAnimation(_ body: () -> Void) {
    body()
}

/// The frozen Foundation on this host has no `String(localized:)`, which the extracted
/// `modeTitle` and `modeExplanation` call. This returns the key itself, which is what a
/// missing translation returns on the platform the client ships to: the two functions
/// are being asked which key they choose, and that answer is the same either way.
extension String {
    init(localized key: String) {
        self = key
    }
}

/// The stand-in the extracted method bodies are compiled inside.
///
/// They are methods of `HakoHomeView` and read its state unqualified - `localMode`,
/// `confirmedMode`, `clashModeList` through `environments`, and the `alert` they raise - so
/// this class supplies exactly those names and nothing else. The bodies are pasted in
/// unchanged; the names around them are what makes that possible. `Probe` inherits it.
@MainActor
class Extracted {
    let clashModeList: [String]
    let clashMode: String
    var localMode: String
    var confirmedMode: String
    /// The state the view raises its alert through; the extracted method assigns it.
    var alert: AlertState?
    var alerts: [String] = []

    init(clashModeList: [String], clashMode: String) {
        self.clashModeList = clashModeList
        self.clashMode = clashMode
        localMode = clashMode
        confirmedMode = clashMode
    }

    /// The shape `selectClashMode` reads the list through.
    struct Client {
        let clashModeList: [String]
    }

    var environments: Environments { Environments(commandClient: Client(clashModeList: clashModeList)) }

    struct Environments {
        let commandClient: Client
    }
"""


HARNESS_FOOTER = """\
}

/// The state the extracted methods reach for, and the two questions the cases ask of them.
@MainActor
final class Probe: Extracted {
    init(modes: [String], reported: String) {
        super.init(clashModeList: modes, clashMode: reported)
    }

    var selection: String {
        currentMode(in: clashModeList)
    }

    func pickerModes() -> [String]? {
        conventionalModes(in: clashModeList)
    }

    /// The label the picker draws on a third, and the caption the fallback row would.
    func label(_ mode: String) -> String {
        modeTitle(mode)
    }

    func caption(_ mode: String) -> String? {
        modeExplanation(mode)
    }

    func labels() -> [String] {
        (pickerModes() ?? []).map { modeTitle($0) }
    }

    func tap(_ mode: String) {
        selectClashMode(mode)
    }
}
"""


def opened(method: str) -> str:
    """The declaration with `private` dropped from its own `func` line.

    Not a semantic change: inside `HakoHomeView` those methods are reachable from the
    view's whole file, which is what `private` means on a member of a type, and `Probe`
    stands in for that file. Widening the declaration is what lets the harness call it
    without a second copy of the body.
    """
    return re.sub(r"^(\s*)private func ", r"\1func ", method, count=1)


# The keys the three conventional modes are labelled with, and the explanations the
# fallback rows carry. Read from the view by the extraction; looked up in the catalogue
# here, so the gate can say what a Chinese reader sees without a bundle to load.
CATALOGUE_KEYS = (
    "Rules",
    "Global",
    "Direct",
    "Split traffic by the profile's rules",
    "Send every connection through the proxy",
    "Send every connection out directly",
)


def catalogue_entries(catalog_path: str) -> str:
    """Swift source for the `[String: String]` of key -> zh-Hans, as escaped scalars.

    Escaped rather than literal so the generated file stays ASCII on a host whose
    compiler output passes through a console code page that is not UTF-8.
    """
    with open(catalog_path, "r", encoding="utf-8") as handle:
        catalogue = json.load(handle)
    strings = catalogue.get("strings", {})
    lines = []
    for key in CATALOGUE_KEYS:
        entry = strings.get(key)
        if entry is None:
            raise ExtractionError(
                "Localizable.xcstrings has no entry for %r - a mode label would render in "
                "English" % key
            )
        localizations = entry.get("localizations", {})
        unit = localizations.get("zh-Hans", {}).get("stringUnit")
        if not unit or not unit.get("value"):
            raise ExtractionError(
                "Localizable.xcstrings has no zh-Hans value for %r" % key
            )
        escaped = "".join("\\u{%04x}" % ord(character) for character in unit["value"])
        lines.append('    "%s": "%s",' % (key.replace('"', '\\"'), escaped))
    return "\n".join(lines)


def build_harness(methods: list[str], catalogue: str) -> str:
    """The extracted text, normalised to one level of indent inside `class Extracted`.

    The declarations are lifted with whatever indentation the view gives them; stripping
    it first keeps the generated file readable without changing a character of what Swift
    sees.
    """
    lines = [
        "    " + line.strip() if line.strip() else ""
        for method in methods
        for line in (opened(method).splitlines() + [""])
    ]
    harness = HARNESS_HEADER + "\n".join(lines) + "\n" + HARNESS_FOOTER + CHECK_MAIN
    harness = harness.replace("CATALOGUE_ENTRIES", catalogue)
    if "CATALOGUE_ENTRIES" in harness:
        raise ExtractionError("the catalogue placeholder survived substitution")
    return harness


CHECK_MAIN = r"""
// MARK: - The cases this change has to hold

struct CheckFailure: Error, CustomStringConvertible {
    let description: String
}

func expect(_ condition: Bool, _ description: String) throws {
    if !condition { throw CheckFailure(description: description) }
}

@MainActor
func expectEqual<T: Equatable>(_ actual: T, _ expected: T, _ description: String) throws {
    if actual != expected {
        throw CheckFailure(description: "\(description): expected \(expected), got \(actual)")
    }
}

/// `selectClashMode` sends through a `Task`, so what it sent and whether it rolled back are
/// only observable after the main actor has run it. Yielding is what lets it.
@MainActor
func settle() async {
    await Task.yield()
    try? await Task.sleep(nanoseconds: 200_000_000)
}

/// The Chinese the shipped catalogue gives each key `modeTitle` returns, read out of
/// `Localizable.xcstrings` by the gate that generated this file. The extracted methods are
/// asked for their own keys - `String(localized:)` is a bundle lookup, and this host has no
/// bundle - and the pair is what a reader actually sees on the three thirds.
let catalogue: [String: String] = [
CATALOGUE_ENTRIES
]

@MainActor
func chinese(for key: String) throws -> String {
    guard let value = catalogue[key] else {
        throw CheckFailure(description: "the catalogue has no zh-Hans entry for \(key)")
    }
    return value
}

@MainActor
func runChecks() async throws -> [String] {
    var ran: [String] = []

    // 1. The standard three, the order the core conventionally reports.
    do {
        let probe = Probe(modes: ["Rule", "Global", "Direct"], reported: "Rule")
        try expectEqual(probe.pickerModes(), ["Rule", "Global", "Direct"], "standard three are compact")
        try expectEqual(probe.selection, "Rule", "the core's reported mode is the marked third")
        try expectEqual(
            try probe.labels().map { try chinese(for: $0) },
            ["\u{89c4}\u{5219}", "\u{5168}\u{5c40}", "\u{76f4}\u{8fde}"],
            "the three thirds read 规则 / 全局 / 直连"
        )
        try expect(probe.pickerModes()?.count == 3, "three equal thirds")
        ran.append("standard three")
    }

    // 2. The order the core reports is not the order the picker shows.
    do {
        CommandTarget.sent = []
        let probe = Probe(modes: ["Global", "Direct", "Rule"], reported: "Global")
        try expectEqual(probe.pickerModes(), ["Rule", "Global", "Direct"], "the picker fixes the order")
        try expectEqual(probe.selection, "Global", "the marked third follows the core, not the slot")
        probe.tap(probe.pickerModes()![2])
        await settle()
        try expectEqual(CommandTarget.sent.last, "Direct", "a tap sends the core's own spelling")
        ran.append("reported order")
    }

    // 3. Case is the configuration's to choose.
    do {
        CommandTarget.sent = []
        let probe = Probe(modes: ["rule", "GLOBAL", "Direct"], reported: "global")
        try expectEqual(probe.pickerModes(), ["rule", "GLOBAL", "Direct"], "case does not decide the shape")
        try expectEqual(probe.selection, "GLOBAL", "the marked third is the core's spelling")
        try expectEqual(
            try probe.labels().map { try chinese(for: $0) },
            ["\u{89c4}\u{5219}", "\u{5168}\u{5c40}", "\u{76f4}\u{8fde}"],
            "a lower-case core mode still reads in Chinese"
        )
        probe.tap(probe.pickerModes()![1])
        await settle()
        try expectEqual(CommandTarget.sent.last, "GLOBAL", "the core's spelling is what goes back")

        // A third whose label is not its value. Without this, every tap above sends a string
        // that already matches the core's spelling, and `canonicalMode` could be dropped from
        // the send path without any of them noticing.
        CommandTarget.sent = []
        let labelled = Probe(modes: ["Rule", "Global", "Direct"], reported: "Rule")
        try expectEqual(labelled.label("Global"), "Global", "the label is the key, not the value")
        labelled.tap("global")
        await settle()
        try expectEqual(CommandTarget.sent.last, "Global", "a lower-case tap sends the core's spelling")
        try expectEqual(labelled.selection, "Global", "and the third it marks is the core's spelling")
        ran.append("case")
    }

    // 4. A fourth mode is never dropped: the compact shape declines the list.
    do {
        let probe = Probe(modes: ["Rule", "Global", "Direct", "Block"], reported: "Rule")
        try expectEqual(probe.pickerModes(), nil, "a custom mode falls back to the list")
        try expectEqual(probe.selection, "Rule", "the fallback still marks the current mode")
        try expectEqual(probe.label("Block"), "Block", "an unknown mode is shown as the core named it")
        try expectEqual(probe.caption("Block"), nil, "an unknown mode grows no borrowed explanation")
        try expectEqual(
            try chinese(for: probe.caption("Global") ?? ""),
            "\u{6240}\u{6709}\u{8fde}\u{63a5}\u{5747}\u{8d70}\u{4ee3}\u{7406}",
            "the fallback row keeps its explanation"
        )
        ran.append("custom mode")
    }

    // 5. Fewer than three: never compact, and a single mode is still no control at all.
    do {
        let probe = Probe(modes: ["Rule"], reported: "Rule")
        try expectEqual(probe.pickerModes(), nil, "one mode is not the compact three")
        try expect(probe.clashModeList.count <= 1, "one mode draws no selector")
        ran.append("single mode")
    }

    // 6. A switch the core refuses is given back to the mode it last reported.
    do {
        CommandTarget.sent = []
        CommandTarget.failure = NSError(domain: "probe", code: 1)
        let probe = Probe(modes: ["Rule", "Global", "Direct"], reported: "Rule")
        probe.tap(probe.pickerModes()![1])
        await settle()
        try expectEqual(probe.alert?.action, "set clash mode", "a refused switch raises its alert")
        try expectEqual(probe.selection, "Rule", "a refused switch rolls back to the core's mode")
        CommandTarget.failure = nil
        ran.append("failed switch rolls back")
    }

    // 7. A switch the core accepts stays where the reader put it, before the core reports.
    do {
        CommandTarget.sent = []
        let probe = Probe(modes: ["Rule", "Global", "Direct"], reported: "Rule")
        probe.tap(probe.pickerModes()![2])
        await settle()
        try expectEqual(probe.selection, "Direct", "the choice is optimistic until the core reports")
        try expectEqual(CommandTarget.sent.last, "Direct", "and it was sent")
        try expect(probe.alert == nil, "an accepted switch raises nothing")
        ran.append("optimistic selection")
    }

    // 8. Every list that is not exactly the conventional three is declined.
    do {
        let walls: [[String]] = [
            [],
            ["Rule"],
            ["Rule", "Global"],
            ["Rule", "Global", "Direct", "Block"],
            ["Rule", "Global", "DIRECT", "direct"],
            ["Rule", "Rule", "Global"],
            ["Rule", "Global", "Proxy"],
            ["rule", "global"],
        ]
        for wall in walls {
            let probe = Probe(modes: wall, reported: wall.first ?? "")
            try expectEqual(probe.pickerModes(), nil, "must decline \(wall)")
        }
        ran.append("declined lists")
    }

    return ran
}

let ran = try await runChecks()
for name in ran { print("  [ok] " + name) }
print("  compact outbound-mode picker: \(ran.count) case(s) PASS")
"""


def find_swiftc(explicit: str | None) -> str:
    if explicit:
        return explicit
    found = shutil.which("swiftc")
    if found:
        return found
    candidates = [
        r"C:\Users\Jie\AppData\Local\Programs\Swift\Toolchains\6.3.3+Asserts\usr\bin\swiftc.exe",
    ]
    for candidate in candidates:
        if os.path.exists(candidate):
            return candidate
    raise SystemExit("swiftc not found; pass --swiftc PATH")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=os.getcwd(), help="repository root")
    parser.add_argument("--swiftc", default=None, help="the compiler to use")
    parser.add_argument("--explain", action="store_true", help="print the extracted source and stop")
    options = parser.parse_args()

    view_path = os.path.join(options.root, VIEW_FILE)
    if not os.path.exists(view_path):
        print("FAIL: %s does not exist" % view_path)
        return 2
    with open(view_path, "r", encoding="utf-8") as handle:
        source = handle.read()

    catalog_path = os.path.join(options.root, CATALOG_FILE)
    if not os.path.exists(catalog_path):
        print("FAIL: %s does not exist" % catalog_path)
        return 2

    try:
        methods = [extract_method(source, name, view_path) for name in REQUIRED_METHODS]
        catalogue = catalogue_entries(catalog_path)
    except ExtractionError as error:
        print("FAIL: %s" % error)
        return 1
    except (OSError, ValueError) as error:
        print("FAIL: %s is not a readable string catalogue: %s" % (catalog_path, error))
        return 2

    harness = build_harness(methods, catalogue)
    if options.explain:
        print(harness)
        return 0

    swiftc = find_swiftc(options.swiftc)
    with tempfile.TemporaryDirectory(prefix="compact-mode-picker-") as scratch:
        harness_path = os.path.join(scratch, "harness.swift")
        with open(harness_path, "w", encoding="utf-8") as handle:
            handle.write(harness)

        binary = os.path.join(scratch, "harness.exe" if os.name == "nt" else "harness")
        compile_result = subprocess.run(
            [swiftc, "-O", "-o", binary, harness_path],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        if compile_result.returncode != 0:
            print("FAIL: the extracted methods do not compile")
            print(compile_result.stdout)
            print(compile_result.stderr)
            return 1

        run_result = subprocess.run(
            [binary],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        sys.stdout.write(run_result.stdout)
        if run_result.returncode != 0:
            sys.stderr.write(run_result.stderr)
            print("FAIL: a case did not hold")
            return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
