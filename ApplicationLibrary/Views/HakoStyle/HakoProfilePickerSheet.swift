/// The original compact subtitle: type, remaining traffic, update age and a short expiry date.
/// Both phone rows keep one subtitle line so their original card height and spacing are preserved.
private struct HakoProfileMetadata: View {
    @Environment(\.locale) private var locale

    let profile: ProfilePreview

    var body: some View {
        TimelineView(.periodic(from: .now, by: 60)) { context in
            metadata(now: context.date)
        }
        .font(.caption)
        .foregroundStyle(.secondary)
    }

    private func metadata(now: Date) -> some View {
        let caption = SubscriptionQuotaCaption.content(
            isRemote: profile.type == .remote,
            info: profile.subscriptionInfo,
            capturedAt: profile.subscriptionInfoUpdatedAt,
            lastUpdated: profile.lastUpdated,
            now: now
        )
        return HStack(spacing: 8) {
            HStack(spacing: 4) {
                Image(systemName: profile.type.presentationSymbol)
                    .font(.system(size: 12))
                Text(profile.type.presentationLabel)
            }
            .layoutPriority(1)

            remainingTrafficInfo

            if profile.type == .remote, let lastUpdated = profile.lastUpdated {
                HStack(spacing: 4) {
                    Image(systemName: "clock.fill")
                        .font(.system(size: 12))
                    Text(lastUpdated.relativeFormat(forPickerRow: locale, relativeTo: now))
                }
                .layoutPriority(1)
            }

            if let expiry = caption?.expiry {
                let date = Self.expiryDay(expiry.date)
                let format = expiry.expired ? String(localized: "Expired on %@") : String(localized: "Expires on %@")
                Text(verbatim: String(format: format, date))
                    .foregroundStyle(expiry.expired ? Color.red : Color.secondary)
                    .layoutPriority(1)
            }
        }
        .lineLimit(1)
        .minimumScaleFactor(0.8)
    }

    /// The bare month/day an expiry caption shares its line with.
    ///
    /// Kept in a plain method because `@ViewBuilder` accepts `let` bindings but not assignment
    /// statements, and configuring a `DateFormatter` is a sequence of assignments. The formatter is
    /// built per call: this runs once per visible profile row, and a cached non-`Sendable`
    /// formatter would be the more fragile choice.
    private static func expiryDay(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "MM/dd"
        return formatter.string(from: date)
    }

    @ViewBuilder
    private var remainingTrafficInfo: some View {
        if let remaining = profile.subscriptionInfo?.remainingBytes {
            Text(verbatim: String(format: String(localized: "%@ left"),
                                  Int64.remainingTrafficText(remaining)))
        }
    }
}

private extension Int64 {
    /// A quota remainder as the configuration row spells it.
    ///
    /// Written here rather than taken from `ByteCountFormatter`: that formatter spells units out
    /// in full for several locales and returns "Zero KB" for nothing at all, and neither fits a
    /// caption that shares its line with two other items. The units are the decimal ones the
    /// panels themselves report against.
    ///
    /// - Zero is "0 B", not "0 GB": a remainder of nothing is a real value the row must state.
    /// - A negative value cannot reach here - `remainingBytes` clamps at zero - but is clamped
    ///   anyway so the caption can never read "-1 GB".
    /// - Precision is one decimal below ten and none from ten up: "1.2 TB" and "8.6 GB" keep
    ///   their shape, while ordinary quotas stay short - "286 GB", "840 MB".
    static func remainingTrafficText(_ bytes: Int64) -> String {
        // `Swift.max`, not `max`: the file's imports bring a `max` of their own, which the
        // `bytes` parameter would otherwise be handed to.
        let bytes = Swift.max(0, bytes)
        guard bytes >= 1000 else {
            return "\(bytes) B"
        }
        // Descending, so the first threshold the remainder clears is its unit.
        let units: [(threshold: Int64, divisor: Double, name: String)] = [
            (1_000_000_000_000, 1_000_000_000_000, "TB"),
            (1_000_000_000, 1_000_000_000, "GB"),
            (1_000_000, 1_000_000, "MB"),
            (1000, 1000, "KB"),
        ]
        let unit = units.first { bytes >= $0.threshold }!
        // Quantised at the one decimal the caption ever shows, so a value that rounds up to ten
        // is counted in tens and spelled "10 GB" rather than "10.0 GB".
        let rounded = (Double(bytes) / unit.divisor * 10).rounded() / 10
        let decimals = rounded < 10 ? 1 : 0
        return "\(rounded.formatted(.number.precision(.fractionLength(decimals)))) \(unit.name)"
    }
}

// MARK: - Relative time

private extension Date {
    /// Use the view's locale and timeline instant for both timestamp labels.
    func relativeFormat(forPickerRow locale: Locale, relativeTo now: Date) -> String {
        let formatter = RelativeDateTimeFormatter()
        formatter.locale = locale
        formatter.unitsStyle = locale.identifier.hasPrefix("zh") ? .full : .abbreviated
        formatter.dateTimeStyle = .numeric
        return formatter.localizedString(for: self, relativeTo: now)
    }
}
