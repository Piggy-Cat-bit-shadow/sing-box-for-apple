//
//  HakoProfilePickerSheet.swift
//  ApplicationLibrary
//
//  The phone's configuration centre.
//
//  # Where this comes from
//
//  This is the fork's profile picker, from `hako-ui` @ `c1935cf`, resolved for iOS. It is the file
//  that carries the remaining-quota row: the item that reads the panel's `subscription-userinfo`
//  remainder out of the `ProfilePreview` snapshot the row already holds and prints it between the
//  configuration's type and its last-update time.
//
//  # Why it is a separate file from `ProfilePickerSheet`
//
//  An iPad and a Mac can both open the profile picker, and the requirement for both is upstream's
//  presentation with nothing added. The remaining-quota row is phone presentation. One file cannot
//  be both byte-identical to upstream and carry a new row, so
//  `ApplicationLibrary/Views/Dashboard/Cards/ProfilePickerSheet.swift` is restored to upstream and
//  this owns the phone's version.
//
//  The **data** chain is not forked: `SubscriptionInfo`, `RemoteProfileFetcher`,
//  `RemoteProfileRefresh`, `RemoteRefreshApplier` and the `add_subscription_info` migration are
//  shared, covered by `Tests/HakoSubscriptionUsage`, and read here through
//  `ProfilePreview.subscriptionInfo`.
//
//  # What is different from the official picker
//
//  The compact quota and expiry presentation. Everything else - the list, edit mode,
//  reorder, delete, QR share, export, and editor - follows the upstream picker. See `docs/HAKO-UI-MIGRATION-MATRIX.md`.
//
//  Originally generated by `scripts/dev/make_hako_profile_picker.py`. Preserve the later manual
//  repairs when comparing any regenerated candidate.
//

import Library
import QRCode
import SwiftUI

@MainActor
struct HakoProfilePickerSheet: View {
    @EnvironmentObject private var environments: ExtensionEnvironments
    @Environment(\.dismiss) private var dismiss

    @Binding var profileList: [ProfilePreview]
    @Binding var selectedProfileID: Int64

        // The original's `#if !os(macOS)` / `#else` (its lines 16-21): `EditMode` is an
        // iOS/tvOS `EnvironmentValue` that macOS does not declare, and the Mac tracks the same
        // idea with its own `Bool` plus the row width it sizes against.
        #if !os(macOS)
        @State private var editMode: EditMode = .inactive
        #else
        @State private var isEditing = false
        @State private var rowWidth: CGFloat = 400
        #endif
    @State private var profileToEdit: Profile?
    @State private var alert: AlertState?
    @State private var showNewProfile = false
    @State private var isUpdatingAll = false

    private var isEditingActive: Bool {
            #if !os(macOS)
            editMode.isEditing
            #else
            isEditing
            #endif
    }

    /// What the row is told about edit state, on the platform that has to be told.
    ///
    /// The row reaches `EditMode` itself on iOS and is handed the value on the Mac, so both the
    /// name and the source differ by platform - and an argument label cannot carry a directive.
    /// One accessor keeps the call site platform-free.
    private var rowIsEditing: Bool {
        #if os(macOS)
            isEditing
        #else
            isEditingActive
        #endif
    }
    var body: some View {
        // The original branches on the platform here, not inside a version check: its `iOSBody`
        // and `legacyIOSBody` are both iOS-only, and the Mac has `nonIOSBody`. The port kept only
        // the iOS pair, which is why every unguarded `editMode` below had no Mac counterpart to
        // fall into. `iOSBody` and `legacyIOSBody` still own the `#available` choice between them.
        #if os(iOS)
            if #available(iOS 26, *) {
                iOSBody
                    .environment(\.editMode, $editMode)
            } else {
                legacyIOSBody
                    .environment(\.editMode, $editMode)
            }
        #else
            nonIOSBody
        #endif
    }

    // The original keeps every one of these behind `#if os(iOS)` (its lines 51-133): `iOSBody`,
    // `legacyIOSBody` and the four list shapes they compose all build `HakoProfilePickerRow` and
    // `LegacyProfilePickerRow`, which are themselves iOS-only for the same reason - they read
    // `EditMode`. `listContent` below is the part both platforms share, and it is what the Mac's
    // `nonIOSBody` presents.
    #if os(iOS)
        @available(iOS 26, *)
        private var iOSBody: some View {
            iOSListContent
                .toolbar {
                    ToolbarItem(placement: .primaryAction) {
                        // Add and edit belong together in one capsule, which is how the rest
                        // of this client presents a page's own actions. The add control used
                        // to exist only on the Home card, so a user already looking at their
                        // configurations had to close this sheet to add one.
                        HakoActionGroup {
                            if !remoteProfiles.isEmpty {
                                HakoActionItem(
                                    systemImage: "arrow.clockwise",
                                    label: String(localized: "Update All"),
                                    isBusy: isUpdatingAll
                                ) {
                                    Task {
                                        await updateAllProfiles()
                                    }
                                }
                                .accessibilityIdentifier("hako.profile.updateAll")
                            }
                            HakoActionItem(
                                systemImage: "plus",
                                label: String(localized: "Add Configuration")
                            ) {
                                showNewProfile = true
                            }
                            // The identifier the add entry point has always carried. It moved
                            // from the home's card, where it sat beside a picker and two other
                            // actions, to the centre, where adding a configuration belongs.
                            .accessibilityIdentifier("hako.profile.add")
                            HakoActionItem(
                                systemImage: editMode.isEditing ? "checkmark" : "pencil",
                                label: editMode.isEditing
                                    ? String(localized: "Done")
                                    : String(localized: "Edit")
                            ) {
                                withAnimation {
                                    editMode = editMode.isEditing ? .inactive : .active
                                }
                            }
                        }
                    }
                }
                .sheet(isPresented: $showNewProfile, onDismiss: {
                    environments.profileUpdate.send()
                }, content: {
                    HakoNewProfileSheetContent()
                        .environmentObject(environments)
                })
                .sheet(item: $profileToEdit) { profile in
                    NavigationSheet(title: "Edit Profile") {
                        HakoEditProfileView()
                            .environmentObject(profile)
                            .environmentObject(environments)
                            .hakoModalClose()
                    }
                }
                .alert($alert)
        }

        @available(iOS 26, *)
        @ViewBuilder
        private var iOSListContent: some View {
            if editMode.isEditing {
                iOSEditingList
            } else {
                iOSNormalList
            }
        }

        @available(iOS 26, *)
        private var iOSEditingList: some View {
            listContent
        }

        @available(iOS 26, *)
        private var iOSNormalList: some View {
            List {
                ForEach(profileList, id: \.id) { profile in
                    HakoProfilePickerRow(
                        profile: profile,
                        isSelected: profile.id == selectedProfileID,
                        isEditing: rowIsEditing,
                        alert: $alert,
                        onSelect: {
                            selectedProfileID = profile.id
                            dismiss()
                        },
                        onEdit: {
                            profileToEdit = profile.origin
                        },
                        onUpdate: {
                            await updateProfile(profile)
                        }
                    )
                    .environmentObject(environments)
                    .listRowBackground(Color.clear)
                    .listRowSeparator(.hidden)
                    .listRowInsets(EdgeInsets(top: 2, leading: 16, bottom: 2, trailing: 16))
                }
            }
            .listStyle(.plain)
        }

        private var legacyIOSBody: some View {
            legacyListContent
                .toolbar {
                    ToolbarItem(placement: .primaryAction) {
                        Button(editMode.isEditing ? "Done" : "Edit") {
                            withAnimation {
                                editMode = editMode.isEditing ? .inactive : .active
                            }
                        }
                    }
                }
                .sheet(item: $profileToEdit) { profile in
                    NavigationSheet(title: "Edit Profile") {
                        HakoEditProfileView()
                            .environmentObject(profile)
                            .environmentObject(environments)
                            .hakoModalClose()
                    }
                }
                .alert($alert)
        }
    #endif

    // The original's `#if !os(iOS)` branch (its lines 135-198), ported as the Mac's own body.
    // The difference is deliberate and matches upstream: the Mac tracks edit state with
    // `isEditing`, because `EditMode` does not exist there, and it presents the editor in its own
    // sheet rather than the phone's modal. `listContent` is shared by both.
    #if os(macOS)
        private var nonIOSBody: some View {
            listContent
                .safeAreaInset(edge: .bottom) {
                    VStack(spacing: 0) {
                        Divider()
                        HStack {
                            Spacer()
                            Button("Cancel") {
                                dismiss()
                            }
                            .keyboardShortcut(.escape, modifiers: [])
                            if isEditing {
                                Button("Done") {
                                    withAnimation {
                                        isEditing = false
                                    }
                                }
                                .buttonStyle(.borderedProminent)
                            } else {
                                Button("Edit") {
                                    withAnimation {
                                        isEditing = true
                                    }
                                }
                                .buttonStyle(.borderedProminent)
                            }
                        }
                        .padding()
                        .background(Color(NSColor.controlBackgroundColor))
                    }
                }
                .sheet(item: $profileToEdit) { profile in
                    NavigationSheet {
                        HakoEditProfileView()
                            .environmentObject(profile)
                            .environmentObject(environments)
                    }
                    .frame(minWidth: 500, minHeight: 400)
                }
                .alert($alert)
        }
    #endif

    private var listContent: some View {
            List {
                ForEach(profileList, id: \.id) { profile in
                    HakoProfilePickerRow(
                        profile: profile,
                        isSelected: profile.id == selectedProfileID,
                        // The Mac arm of the row takes its edit state as a value - it has no
                        // `EditMode` to read - so the property below supplies `nonIOSBody`'s own
                        // flag there and the row's `EditMode` read on iOS. A directive cannot sit
                        // in an argument list, so the platform choice lives in the accessor.
                        isEditing: rowIsEditing,
                        alert: $alert,
                        onSelect: {
                            selectedProfileID = profile.id
                            dismiss()
                        },
                        onEdit: {
                            profileToEdit = profile.origin
                        },
                        onUpdate: {
                            await updateProfile(profile)
                        }
                    )
                    .environmentObject(environments)
                    .listRowBackground(Color.clear)
                    .listRowSeparator(.hidden)
                    .listRowInsets(EdgeInsets(top: 2, leading: 16, bottom: 2, trailing: 16))
                }
                .onMove(perform: moveProfile)
                .onDelete(perform: deleteProfile)
            }
            .listStyle(.plain)
    }

    // The legacy trio belongs with `legacyIOSBody`, which is already inside `#if os(iOS)` above:
    // all three read `editMode` and build `LegacyProfilePickerRow`, and the Mac has no pre-26
    // layout for them to serve.
    #if os(iOS)
        @ViewBuilder
        private var legacyListContent: some View {
            if editMode.isEditing {
                legacyEditingList
            } else {
                legacyNormalList
            }
        }

        private var legacyEditingList: some View {
            List {
                ForEach(profileList, id: \.id) { profile in
                    LegacyProfilePickerRow(
                        profile: profile,
                        isSelected: profile.id == selectedProfileID,
                        alert: $alert,
                        onSelect: {
                            selectedProfileID = profile.id
                            dismiss()
                        },
                        onEdit: {
                            profileToEdit = profile.origin
                        },
                        onUpdate: {
                            await updateProfile(profile)
                        }
                    )
                    .environmentObject(environments)
                }
                .onMove(perform: legacyMoveProfile)
                .onDelete(perform: legacyDeleteProfile)
            }
        }

        private var legacyNormalList: some View {
            List {
                ForEach(profileList, id: \.id) { profile in
                    LegacyProfilePickerRow(
                        profile: profile,
                        isSelected: profile.id == selectedProfileID,
                        alert: $alert,
                        onSelect: {
                            selectedProfileID = profile.id
                            dismiss()
                        },
                        onEdit: {
                            profileToEdit = profile.origin
                        },
                        onUpdate: {
                            await updateProfile(profile)
                        }
                    )
                    .environmentObject(environments)
                }
            }
        }
    #endif

        private func legacyMoveProfile(from source: IndexSet, to destination: Int) {
            profileList.move(fromOffsets: source, toOffset: destination)
            for (index, profile) in profileList.enumerated() {
                profileList[index].order = UInt32(index)
                profile.origin.order = UInt32(index)
            }
            Task {
                do {
                    try await ProfileManager.update(profileList.map(\.origin))
                    environments.profileUpdate.send()
                } catch {
                    // Handle error silently
                }
            }
        }

        private func legacyDeleteProfile(at offsets: IndexSet) {
            let profilesToDelete = offsets.map { profileList[$0].origin }
            profileList.remove(atOffsets: offsets)
            Task {
                do {
                    _ = try await ProfileManager.delete(profilesToDelete)
                    environments.emptyProfiles = profileList.isEmpty
                    environments.profileUpdate.send()
                } catch {
                    // Handle error silently
                }
            }
        }


    private func updateProfile(_ profile: ProfilePreview) async {
        do {
            try await profile.origin.updateRemoteProfile()
            environments.profileUpdate.send()
        } catch {
            alert = AlertState(action: "update remote profile", error: error)
        }
    }

    /// The remote configurations this page can fetch.
    private var remoteProfiles: [ProfilePreview] {
        profileList.filter { $0.type == .remote }
    }

    /// Fetch every remote configuration.
    ///
    /// The same call a single row makes, once per remote configuration. It reports progress
    /// through the page's own state, so the rows say what is happening rather than the page
    /// going quiet for as long as the slowest download takes.
    private func updateAllProfiles() async {
        guard !isUpdatingAll else {
            return
        }
        isUpdatingAll = true
        defer { isUpdatingAll = false }
        for profile in remoteProfiles {
            await updateProfile(profile)
        }
    }

    private func moveProfile(from source: IndexSet, to destination: Int) {
        profileList.move(fromOffsets: source, toOffset: destination)
        for (index, profile) in profileList.enumerated() {
            profileList[index].order = UInt32(index)
            profile.origin.order = UInt32(index)
        }
        Task {
            do {
                try await ProfileManager.update(profileList.map(\.origin))
                environments.profileUpdate.send()
            } catch {
                // Handle error silently
            }
        }
    }

    private func deleteProfile(at offsets: IndexSet) {
        let profilesToDelete = offsets.map { profileList[$0].origin }
        profileList.remove(atOffsets: offsets)
        Task {
            do {
                _ = try await ProfileManager.delete(profilesToDelete)
                environments.emptyProfiles = profileList.isEmpty
                environments.profileUpdate.send()
            } catch {
                // Handle error silently
            }
        }
    }

}

// MARK: - HakoProfilePickerRow

// The original declares this row at module scope with **no** guard on the type itself (its line
// 506): the platform differences live inside it, one condition per member - `editMode` behind
// `#if !os(macOS)`, the row width and `ViewAnchor` behind `#if os(macOS)`, the focus and move
// state behind `#if os(tvOS)`. The Mac reaches it from the shared `listContent`, which is why an
// outer guard here would break the platform the guards are distinguishing.
private struct HakoProfilePickerRow: View {
    @EnvironmentObject private var environments: ExtensionEnvironments
    @Environment(\.locale) private var locale

    // The original guards this property with `#if !os(macOS)` (its lines 508-510): `EditMode` is
    // an iOS/tvOS `EnvironmentValue` that macOS does not declare. The row reports `isEditing` as
    // the stored value below on both platforms, so this only feeds the iOS accessor.
    #if !os(macOS)
        @Environment(\.editMode) private var editMode
    #endif

    let profile: ProfilePreview
    let isSelected: Bool
    // The row takes its edit state as a value on BOTH platforms, though upstream reaches it two
    // ways: the original reads `EditMode` from the environment on iOS and is handed a `Bool` by
    // the Mac's list. Taking the value keeps one construction site instead of a directive in an
    // argument list, which Swift does not allow - the state still comes from `rowIsEditing`, so
    // what the row renders is unchanged on either platform.
    let isEditing: Bool
    @Binding var alert: AlertState?
    let onSelect: () -> Void
    let onEdit: () -> Void
    let onUpdate: () async -> Void

    // The `EditMode`-backed answer, on the platform that has `EditMode`. The row's `isEditing` is
    // a stored value both platforms set, so this keeps its own name rather than shadowing it.
    #if !os(macOS)
        private var editModeIsEditing: Bool {
            editMode?.wrappedValue.isEditing ?? false
        }
    #endif
    @State private var isUpdating = false
    @State private var showQRCode = false
    @State private var showQRSShare = false
    @State private var qrsShareData: Data?
    // `ProfileAnyExportDocument` is declared under `#if !os(tvOS)`
    // (`Library/Database/Profile+Transferable.swift:280`) and the `.fileExporter` beside this is its only
    // reader, so both take that condition - the same one the original guards these lines with
    // (`up-hako@c1935cf .../Dashboard/Cards/ProfilePickerSheet.swift:549-552`). `ApplicationLibrary` is
    // built for `appletvos` too, so without it the tvOS slice cannot compile this file.
    #if !os(tvOS)
    @State private var exportDocument: ProfileAnyExportDocument?
    @State private var showExporter = false
    #endif

    var body: some View {
            defaultBody
    }


        @ViewBuilder
        private var defaultBody: some View {
                iOSBody
        }


            private var iOSBody: some View {
                Button {
                    if !isEditing, !isUpdating {
                        onSelect()
                    }
                } label: {
                    rowContent
                        // The same floor a first-level destination row has, so the
                        // configuration list and the menu it is opened from have one rhythm.
                        .frame(minHeight: HakoTheme.Layout.destinationRowTargetHeight)
                }
                .buttonStyle(.plain)
                .disabled(isEditing || isUpdating)
                .sheet(isPresented: $showQRCode) {
                    if let remoteURL = profile.remoteURL {
                        QRCodeSheet(profileName: profile.name, remoteURL: remoteURL)
                    }
                }
                .sheet(
                    isPresented: $showQRSShare,
                    onDismiss: {
                        qrsShareData = nil
                    },
                    content: {
                        if let data = qrsShareData {
                            HakoQRSSheet(profileName: profile.name, profileData: data)
                        } else {
                            ProgressView()
                        }
                    }
                )
                .fileExporter(
                    isPresented: $showExporter,
                    document: exportDocument,
                    contentType: exportDocument?.contentType ?? .data,
                    defaultFilename: exportDocument?.filename
                ) { result in
                    exportDocument = nil
                    if case let .failure(error) = result {
                        alert = AlertState(action: "export profile", error: error)
                    }
                }
            }

        private var rowContent: some View {
            HStack(spacing: HakoTheme.Spacing.row) {

                // The type is what a profile row has to say about itself, so it gets the icon
                // tile the rest of the client uses for "where does this live". The previous
                // leading checkmark said whether the row was selected, which the trailing mark
                // now says without occupying the position that carries information.
                // The first-level icon well, at the first-level size. It was the smaller
                // proxy-group well with a hand-set glyph, which is why the configuration list
                // read as a more compact species of list than the menu it is reached from - the
                // review's "raise the configuration centre's rows and icons to the first-level
                // standard".
                // The review's item: the type icon was indigo, cyan or teal - one colour per
                // kind of profile - which made a list of identically shaped rows read as four
                // categories. The kind is already said in words beside it; the icon is the
                // client's neutral one, like every other row's.
                HakoIconWell(tint: HakoAccentRole.neutral.color, systemImage: profile.type.presentationSymbol)

                VStack(alignment: .leading, spacing: HakoTheme.Typography.rowSubtitleGap(locale)) {
                    Text(profile.name)
                        .font(.body)
                        .foregroundStyle(.primary)
                        .lineLimit(1)

                    profileInfo
                }

                Spacer(minLength: HakoTheme.Spacing.compact)

                if !isEditing {
                    selectionMark
                }

                    if !isEditing {
                        rowMenu
                    }
            }
            .padding(HakoTheme.Spacing.standard)
            .cardStyle()
            .contentShape(Rectangle())
        }

        /// Whether this is the profile the client is using.
        private var selectionMark: some View {
            HakoSelectionMark(isSelected: isSelected)
        }

    private var rowMenu: some View {
        Menu {
            Button {
                onEdit()
            } label: {
                Label("Edit", systemImage: "pencil")
            }

            if profile.type == .remote {
                Button {
                    isUpdating = true
                    Task {
                        await onUpdate()
                        isUpdating = false
                    }
                } label: {
                    Label("Update", systemImage: "arrow.clockwise")
                }
            }

                shareMenu
        } label: {
            Group {
                if isUpdating {
                    ProgressView()
                        .scaleEffect(0.8)
                } else {
                    Image(systemName: "ellipsis")
                        .font(.system(size: 16))
                        .foregroundStyle(.secondary)
                }
            }
            .frame(width: 32, height: 32)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
    }

    private func prepareQRSShare() {
        qrsShareData = nil
        showQRSShare = true
        Task {
            do {
                let data = try await profile.origin.encodedContentDataAsync()
                await MainActor.run {
                    qrsShareData = data
                }
            } catch {
                await MainActor.run {
                    alert = AlertState(action: "prepare QRS share", error: error)
                    showQRSShare = false
                }
            }
        }
    }

        private var shareMenu: some View {
            Menu {
                    Button {
                        exportProfile(type: .file)
                    } label: {
                        Label("Save File", systemImage: "square.and.arrow.down")
                    }

                    ShareButtonCompat($alert) {
                        Label("Share File", systemImage: "doc")
                    } itemURL: {
                        try await profile.origin.generateShareFileAsync()
                    }

                    Button {
                        exportProfile(type: .json)
                    } label: {
                        Label("Save Content JSON", systemImage: "square.and.arrow.down")
                    }

                    ShareButtonCompat($alert) {
                        Label("Share Content JSON File", systemImage: "curlybraces")
                    } itemURL: {
                        try await profile.origin.generateJSONShareFileAsync(name: "\(profile.name).json")
                    }

                if profile.type == .remote {
                    Button {
                        showQRCode = true
                    } label: {
                        Label("Share URL as QR Code", systemImage: "qrcode")
                    }
                }

                Button {
                    prepareQRSShare()
                } label: {
                    Label("Share as QRS Code", systemImage: "barcode")
                }
            } label: {
                Label("Share", systemImage: "square.and.arrow.up")
            }
        }

        // `#if !os(tvOS)`, as the original has it (`up-hako@c1935cf
        // .../Dashboard/Cards/ProfilePickerSheet.swift:942-1036`): this function exists to build a
        // `ProfileAnyExportDocument`, which is declared under that condition, and it writes the state
        // pair guarded the same way above it.
        #if !os(tvOS)
        private func exportProfile(type: ExportItemType) {
            Task {
                do {
                    let document: ProfileAnyExportDocument
                    switch type {
                    case .file:
                        let data = try await profile.origin.encodedContentDataAsync()
                        document = ProfileAnyExportDocument(data: data, filename: "\(profile.name).bpf", contentType: .data)
                    case .json:
                        let content = try await profile.origin.readAsync()
                        document = ProfileAnyExportDocument(data: Data(content.utf8), filename: "\(profile.name).json", contentType: .json)
                    }
                    await MainActor.run {
                        exportDocument = document
                        showExporter = true
                    }
                } catch {
                    await MainActor.run {
                        alert = AlertState(action: "export profile", error: error)
                    }
                }
            }
        }
        #endif

    private var profileInfo: some View {
        HakoProfileMetadata(profile: profile)
    }

}

